type Region = 'town-south' | 'town-north' | 'west' | 'beach';
const REGIONS: Region[] = ['town-south', 'town-north', 'west', 'beach'];
// Spatial batches let distant northern blocks simplify while the southern frontage stays detailed.
const townRegion = (z: number): Region => z < -12 ? 'town-north' : 'town-south';
interface Placement { asset: AssetId; part?: string; matrix: Matrix4; region: Region; body: string; slot?: number; lodColor: string }
const Y_AXIS = new Vector3(0, 1, 0);
const place = (x: number, y: number, z: number, yaw = 0, pre?: Matrix4) => {
  const m = new Matrix4().compose(new Vector3(x, y, z), new Quaternion().setFromAxisAngle(Y_AXIS, yaw), new Vector3(1, 1, 1));
  return pre ? m.multiply(pre) : m;
};
const BUILDING_ASSET: Record<string, AssetId> = { sdic: 'T01', worldquant: 'T02', moe: 'T03', aime: 'T04', 'video-rebirth': 'T05', hunyuan: 'T06' };
const LOD_COLOR: Record<string, string> = { T01: '#D6CFC2', T02: '#3A4F66', T03: '#E2D6C2', T04: '#DCD2C0', T05: '#7E624D', T06: '#2B333D', T07: '#DCCDB2', T08: '#4E647D', T09: '#4E647D', T10: '#C9B79C', T11: '#D9CDB8', T12: '#6F8A3A' };

/** Layout -> placements (data only from layout / layout-v4; nothing hand-copied). */
function placements(): Placement[] {
  const out: Placement[] = [];
  BUILDINGS.forEach(({ id, position: [x, y, z], size: [w] }, slot) => {
    const asset = BUILDING_ASSET[id];
    out.push({ asset, matrix: place(x, y, z), region: townRegion(z), body: `building-${id}`, slot, lodColor: LOD_COLOR[asset] });
    out.push({ asset: 'T09', matrix: place(x + w / 2 + 3, y + .13, z + 2.7), region: townRegion(z), body: `board-${id}`, slot, lodColor: LOD_COLOR.T09 });
  });
  // Two palms on the MoE forecourt corners (clear of the bollards at x 14.8 and the plaque at z + 2.7).
  const moe = BUILDINGS.find(b => b.id === 'moe');
  if (moe) {
    const [x, , z] = moe.position, fx = x + moe.size[0] / 2;
    out.push({ asset: 'T12', part: 'a', matrix: place(fx + 1.9, 1.15, z + 4.0, .3), region: townRegion(z), body: 'palm-a', lodColor: LOD_COLOR.T12 });
    // variant b is authored 4 m along glTF +Z; it leans toward the building, so turn it to lean over the avenue.
    out.push({ asset: 'T12', part: 'b', matrix: place(fx + 2.1, 1.15, z - 4.0, Math.PI, new Matrix4().makeTranslation(0, 0, -4)), region: townRegion(z), body: 'palm-b', lodColor: LOD_COLOR.T12 });
  }
  if (LAYOUT_V4) {
    const solids = solidsV4();
    solids.filter(s => s.kind === 'massing').forEach((s, i) => {
      // T07 child i is authored for the i-th massing box (same order, same size; checked against extras below).
      out.push({ asset: 'T07', part: String(i), matrix: place(s.position[0], s.position[1] - s.size[1] / 2, s.position[2], s.position[0] < -40 ? Math.PI : 0),
        region: s.position[0] < -40 ? 'west' : townRegion(s.position[2]), body: `lowrise-${i}`, lodColor: LOD_COLOR.T07 });
    });
    // Beach kiosks and the lifeguard tower face the sea (+Z): glTF +X front turned by -90 deg.
    solids.filter(s => s.kind === 'kiosk').forEach((s, i) => out.push({ asset: 'T10', part: i === 0 ? 'a' : 'b',
      matrix: place(s.position[0], s.position[1] - s.size[1] / 2, s.position[2], -Math.PI / 2), region: 'beach', body: `kiosk-${i}`, lodColor: LOD_COLOR.T10 }));
    solids.filter(s => s.kind === 'tower').forEach((s, i) => out.push({ asset: 'T11',
      matrix: place(s.position[0], s.position[1] - s.size[1] / 2, s.position[2], -Math.PI / 2), region: 'beach', body: `lifeguard-${i}`, lodColor: LOD_COLOR.T11 }));
  }
  return out;
}

/** Top-level part node (direct child of the asset root) of a loaded object. */
function partNode(o: Object3D, root: Object3D): Object3D | null {
  let n: Object3D | null = o;
  while (n && n.parent && n.parent !== root) n = n.parent;
  return n && n.parent === root ? n : null;
}
/** Does a part node belong to the placement (variants: T07_<i>, T10_<a|b>, T12_<a|b>_*)? */
function wantPart(p: Placement, name: string) {
  if (!p.part) return true;
  const tag = name.replace(/^col_/, '').replace(/^T\d\d_/, '');
  return tag === p.part || tag.startsWith(`${p.part}_`) || name === `col_${p.part}_trunk` || name === `col_${p.part}_body` || name === `col_T07_${p.part}`;
}

interface Built {
  regions: Record<Region, { meshes: Mesh[]; lod: Mesh | null; center: Vector3; radius: number }>;
  palms: Mesh[];
  strips: Mesh | null;
  bodies: { name: string; asset: AssetId; interactable?: string; hulls: Float32Array[] }[];
  shadow: Mesh;
  anchors: { asset: AssetId; slot?: number; name: string; position: Vector3; normal: Vector3; up: Vector3; w: number; h: number }[];
  stats: { visibleTris: number; lodTris: number; shadowTris: number; drawMeshes: number; colliders: number };
  dispose: () => void;
}

/** Shared night uniform: glass windows (~60 % lit in the GLB) and the Hunyuan ring follow night.value. The
 * occlusion fade clones materials but re-runs their onBeforeCompile, so the copies share this uniform. */
const glow = { glass: { value: .04 }, ring: { value: .1 } };
function glowMaterial(m: MeshStandardMaterial, uniform: { value: number }, key: string) {
  m.onBeforeCompile = shader => {
    shader.uniforms.uTownGlow = uniform;
    shader.fragmentShader = 'uniform float uTownGlow;\n' + shader.fragmentShader.replace('#include <emissivemap_fragment>', '#include <emissivemap_fragment>\n totalEmissiveRadiance *= uTownGlow;');
  };
  m.customProgramCacheKey = () => `world-town-glow-${key}`;
  m.needsUpdate = true;
}

function build(gltfs: GLTF[]): Built {
  const byId = new Map(IDS.map((id, i) => [id, gltfs[i]] as const));
  const list = placements();
  const geoms = Object.fromEntries(REGIONS.map(r => [r, new Map<string, BufferGeometry[]>()])) as Record<Region, Map<string, BufferGeometry[]>>;
  const lodBoxes = Object.fromEntries(REGIONS.map(r => [r, []])) as Record<Region, BufferGeometry[]>;
  const palmGeoms = new Map<string, BufferGeometry[]>();
  const stripGeoms: BufferGeometry[] = [];
  const shadowGeoms: BufferGeometry[] = [];
  const materials = new Map<string, Material>();
  const bodies: Built['bodies'] = [];
  const anchors: Built['anchors'] = [];
  const v = new Vector3(), m4 = new Matrix4(), nm = new Matrix4();
  const bounds = Object.fromEntries(REGIONS.map(r => [r, { min: new Vector3(1e9, 1e9, 1e9), max: new Vector3(-1e9, -1e9, -1e9) }])) as Record<Region, { min: Vector3; max: Vector3 }>;
  const t07spec = (byId.get('T07')!.scene.getObjectByName('T07')?.userData.spec ?? []) as number[][];
  for (const p of list) {
    const gltf = byId.get(p.asset)!;
    const root = gltf.scene.getObjectByName(p.asset)!;
    gltf.scene.updateMatrixWorld(true);
    if (p.asset === 'T07' && p.part) {
      const spec = t07spec[Number(p.part)], solid = solidsV4().filter(s => s.kind === 'massing')[Number(p.part)];
      if (!spec || Math.abs(spec[2] - solid.size[0]) > .01 || Math.abs(spec[3] - solid.size[2]) > .01 || Math.abs(spec[4] - solid.size[1]) > .01)
        console.warn(`[world-town] T07_${p.part} size differs from massing box`, spec, solid.size);
    }
    const body = { name: p.body, asset: p.asset, interactable: p.asset === 'T09' ? `town-board-${p.slot}` : undefined, hulls: [] as Float32Array[] };
    bodies.push(body);
    root.traverse(o => {
      const part = partNode(o, root);
      if (!part || !wantPart(p, part.name)) return;
      m4.multiplyMatrices(p.matrix, o.matrixWorld);
      if (o.name.startsWith('anchor_') && !(o as Mesh).isMesh) {
        const u = o.userData as { w?: number; h?: number; tiltDeg?: number; normal?: string; lit?: boolean };
        if (u.lit === false || !u.w || !u.h) return;
        const n = u.normal === '-X' ? new Vector3(-1, 0, 0) : new Vector3(1, 0, 0), up = new Vector3(0, 1, 0);
        if (u.tiltDeg) { const t = u.tiltDeg * Math.PI / 180; n.set(Math.cos(t), Math.sin(t), 0); up.set(-Math.sin(t), Math.cos(t), 0); }
        nm.extractRotation(m4);
        anchors.push({ asset: p.asset, slot: p.slot, name: o.name, position: new Vector3().setFromMatrixPosition(m4), normal: n.applyMatrix4(nm).normalize(), up: up.applyMatrix4(nm).normalize(), w: u.w, h: u.h });
        return;
      }
      const mesh = o as Mesh;
      if (!mesh.isMesh) return;
      if (part.name.startsWith('col_')) {
        const pos = mesh.geometry.getAttribute('position'), pts = new Float32Array(pos.count * 3);
        for (let i = 0; i < pos.count; i++) { v.fromBufferAttribute(pos, i).applyMatrix4(m4); pts.set([v.x, v.y, v.z], i * 3); }
        body.hulls.push(pts);
        // shadow proxy: same hull, top lowered to the roof deck where the generator recorded it
        const top = (part.userData as { shadowTopBlenderZ?: number }).shadowTopBlenderZ;
        const g = new BufferGeometry().copy(mesh.geometry as BufferGeometry);
        for (const k of Object.keys(g.attributes)) if (k !== 'position') g.deleteAttribute(k);
        if (top !== undefined) { const a = g.getAttribute('position'); for (let i = 0; i < a.count; i++) if (a.getY(i) > top) a.setY(i, top); }
        g.applyMatrix4(m4); shadowGeoms.push(g);
        if (p.asset !== 'T12') {
          const lg = new BufferGeometry().copy(mesh.geometry as BufferGeometry);
          for (const k of Object.keys(lg.attributes)) if (k !== 'position' && k !== 'normal') lg.deleteAttribute(k);
          if (!lg.getAttribute('normal')) lg.computeVertexNormals();
          lg.applyMatrix4(m4);
          const c = new Color(p.lodColor), col = new Float32Array(lg.getAttribute('position').count * 3);
          for (let i = 0; i < col.length; i += 3) col.set([c.r, c.g, c.b], i);
          lg.setAttribute('color', new BufferAttribute(col, 3));
          lg.setAttribute('lodEmission', new BufferAttribute(new Float32Array(col.length), 3));
          lodBoxes[p.region].push(lg);
        }
        return;
      }
      const mat = mesh.material as MeshStandardMaterial;
      const name = mat.name || 'town_misc';
      if (!materials.has(name)) materials.set(name, mat);
      const g = new BufferGeometry().copy(mesh.geometry as BufferGeometry);
      const keep = p.asset === 'T12' ? ['position', 'normal', '_wind'] : ['position', 'normal'];
      for (const k of Object.keys(g.attributes)) if (!keep.includes(k)) g.deleteAttribute(k);
      g.morphAttributes = {};
      g.applyMatrix4(m4);
      g.computeBoundingBox();
      if (p.asset === 'T12') { const l = palmGeoms.get(name) ?? []; l.push(g); palmGeoms.set(name, l); return; }
      // A distant house still needs windows and a roof to read as a house. The collision hull alone
      // erased those cues and looked like an unfinished box at 60 m. Keep the inexpensive window
      // panes / roof cap in the same single LOD draw, with their original colours and night emission.
      if (name === 'town_glass_dark' || name === 'town_glass_lit' || name === 'town_screen' || name === 'town_roof') {
        const lg = g.clone(), n = lg.getAttribute('position').count;
        const col = new Float32Array(n * 3), emit = new Float32Array(n * 3);
        for (let i = 0; i < n; i++) {
          col.set([mat.color.r, mat.color.g, mat.color.b], i * 3);
          if (name === 'town_glass_lit') emit.set([mat.emissive.r, mat.emissive.g, mat.emissive.b], i * 3);
        }
        lg.setAttribute('color', new BufferAttribute(col, 3));
        lg.setAttribute('lodEmission', new BufferAttribute(emit, 3));
        lodBoxes[p.region].push(lg);
      }
      if (part.name === 'T08_strip') {
        g.setAttribute('slot', new BufferAttribute(new Float32Array(g.getAttribute('position').count).fill(p.slot ?? 0), 1));
        stripGeoms.push(g); return;
      }
      bounds[p.region].min.min(g.boundingBox!.min); bounds[p.region].max.max(g.boundingBox!.max);
      const l = geoms[p.region].get(name) ?? []; l.push(g); geoms[p.region].set(name, l);
    });
  }
  // materials: matte, shared, window glass / ring driven by night
  for (const [name, m] of materials) {
    const s = m as MeshStandardMaterial;
    if (name === 'town_glass_lit') glowMaterial(s, glow.glass, 'glass');
    else if (name === 'town_cyan') glowMaterial(s, glow.ring, 'ring');
    else s.emissiveIntensity = 0;
  }
  let visibleTris = 0, lodTris = 0, shadowTris = 0, drawMeshes = 0;
  const tris = (g: BufferGeometry) => (g.index ? g.index.count : g.getAttribute('position').count) / 3;
  const merged = (list: BufferGeometry[]) => { const g = mergeGeometries(list, false)!; list.forEach(x => x.dispose()); g.computeBoundingSphere(); return g; };
  const regions = {} as Built['regions'];
  for (const r of REGIONS) {
    const meshes: Mesh[] = [];
    for (const [name, list] of geoms[r]) {
      const mesh = new Mesh(merged(list), materials.get(name)!);
      mesh.name = `town-${r}-${name}`;
      mesh.receiveShadow = true; mesh.castShadow = false;
      mesh.userData.occluder = true; mesh.userData.assetId = `town-${r}`;
      meshes.push(mesh); visibleTris += tris(mesh.geometry); drawMeshes++;
    }
    let lod: Mesh | null = null;
    if (lodBoxes[r].length) {
      const material = new MeshStandardMaterial({ vertexColors: true, roughness: .92 });
      material.onBeforeCompile = shader => {
        shader.uniforms.uTownLodGlow = glow.glass;
        shader.vertexShader = 'attribute vec3 lodEmission;\nvarying vec3 vLodEmission;\n' + shader.vertexShader.replace('#include <begin_vertex>', '#include <begin_vertex>\n vLodEmission = lodEmission;');
        shader.fragmentShader = 'uniform float uTownLodGlow;\nvarying vec3 vLodEmission;\n' + shader.fragmentShader.replace('#include <emissivemap_fragment>', '#include <emissivemap_fragment>\n totalEmissiveRadiance += vLodEmission * uTownLodGlow;');
      };
      material.customProgramCacheKey = () => 'town-lod-windows-v1';
      lod = new Mesh(merged(lodBoxes[r]), material);
      lod.name = `town-${r}-lod1`; lod.visible = false; lod.receiveShadow = true;
      lodTris += tris(lod.geometry);
    }
    const b = bounds[r], center = b.min.clone().add(b.max).multiplyScalar(.5);
    regions[r] = { meshes, lod, center, radius: meshes.length ? b.max.distanceTo(center) : 0 };
  }
  const palms: Mesh[] = [];
  for (const [name, list] of palmGeoms) {
    const m = (materials.get(name) ?? new MeshStandardMaterial()) as MeshStandardMaterial;
    if (name.startsWith('palm_leaf')) m.side = DoubleSide;
    const mesh = new Mesh(merged(list), m);
    mesh.name = `town-palms-${name}`; mesh.castShadow = true; mesh.receiveShadow = true; mesh.userData.assetId = 'T12';
    palms.push(mesh); visibleTris += tris(mesh.geometry); drawMeshes++;
  }
  let strips: Mesh | null = null;
  if (stripGeoms.length) {
    const g = merged(stripGeoms);
    g.setAttribute('color', new BufferAttribute(new Float32Array(g.getAttribute('position').count * 3), 3));
    strips = new Mesh(g, new MeshBasicMaterial({ vertexColors: true, toneMapped: false }));
    strips.name = 'town-pillar-strips'; strips.userData.noOcclusionFade = true;
    visibleTris += tris(g); drawMeshes++;
  }
  const shadowGeom = merged(shadowGeoms);
  shadowTris = tris(shadowGeom);
  // Shadow-only caster: never writes colour or depth in the main pass; WorldShadows draws it with its depth material.
  const shadow = new Mesh(shadowGeom, new MeshBasicMaterial({ colorWrite: false, depthWrite: false }));
  shadow.name = 'town-shadow-proxy'; shadow.castShadow = true; shadow.receiveShadow = false;
  shadow.userData.noOcclusionFade = true; shadow.renderOrder = -1;
  const colliders = bodies.reduce((n, b) => n + b.hulls.length, 0);
  const all = [...Object.values(regions).flatMap(r => [...r.meshes, ...(r.lod ? [r.lod] : [])]), ...palms, ...(strips ? [strips] : []), shadow];
  return { regions, palms, strips, bodies, shadow, anchors, stats: { visibleTris, lodTris, shadowTris, drawMeshes, colliders },
    dispose: () => all.forEach(m => { m.geometry.dispose(); }) };
}

/** Quads for canvas faces (signs / year plates / boards), one merged mesh per atlas. */
function quads(items: { position: Vector3; normal: Vector3; up: Vector3; w: number; h: number; row: { v0: number; v1: number } }[], lift = .004) {
  const pos: number[] = [], nor: number[] = [], uv: number[] = [], col: number[] = [], idx: number[] = [];
  items.forEach((q, i) => {
    const right = new Vector3().crossVectors(q.up, q.normal).normalize();
    const c = q.position.clone().addScaledVector(q.normal, lift);
    const corners: [number, number, number, number][] = [[-1, -1, 0, q.row.v0], [1, -1, 1, q.row.v0], [1, 1, 1, q.row.v1], [-1, 1, 0, q.row.v1]];
    for (const [sx, sy, u, vv] of corners) {
      const p = c.clone().addScaledVector(right, sx * q.w / 2).addScaledVector(q.up, sy * q.h / 2);
      pos.push(p.x, p.y, p.z); nor.push(q.normal.x, q.normal.y, q.normal.z); uv.push(u, vv); col.push(1, 1, 1);
    }
    idx.push(i * 4, i * 4 + 1, i * 4 + 2, i * 4, i * 4 + 2, i * 4 + 3);
  });
  const g = new BufferGeometry();
  g.setAttribute('position', new BufferAttribute(new Float32Array(pos), 3));
  g.setAttribute('normal', new BufferAttribute(new Float32Array(nor), 3));
  g.setAttribute('uv', new BufferAttribute(new Float32Array(uv), 2));
  g.setAttribute('color', new BufferAttribute(new Float32Array(col), 3));
  g.setIndex(idx); g.computeBoundingSphere();
  return g;
}

function Board({ slot, position, en, zh }: { slot: number; position: Vec3; en: WorldExperience; zh: WorldExperience }) {
  useInteractable({ id: `town-board-${slot}`, position, radius: 2.4, kind: 'exhibit',
    label: { en: `${en.organization} · ${en.role}`, zh: `${zh.organization} · ${zh.role}` },
    onInteract: () => useWorldStore.setState({ card: { kind: 'experience', id: en.startDate } }) });
  return null;
}

const LIGHT_RADIUS = 9;
export default function WorldTownAssets({ experiences }: { experiences: WorldContent['experiences'] }) {
  const gltfs = useLoader(GLTFLoader, URLS, withDraco) as GLTF[];
  const built = useMemo(() => build(gltfs), [gltfs]);
  useEffect(() => built.dispose, [built]);
  // Visual AND collider are mounted in this same commit, so the greybox can hand over now (spec 15.2).
  useGreyboxClaim('building', 'building-forecourt', ...(LAYOUT_V4 ? ['massing' as const] : []));
  const en = experiences.en, zh = experiences.zh;
  const ids = useMemo(() => BUILDINGS.map(b => b.id), []);
  const canvases = useMemo(() => {
    const signs = built.anchors.filter(a => a.name === 'anchor_sign' && a.slot !== undefined && a.asset < 'T07').sort((a, b) => a.slot! - b.slot!);
    const boards = built.anchors.filter(a => a.name === 'anchor_board');
    const sAtlas: Atlas = signAtlas(signs.map(s => ids[s.slot!]), signs.map(s => s.w / s.h), en, zh);
    const bAtlas = boardAtlas(ids, en, zh);
    const sMesh = new Mesh(quads(signs.map((s, i) => ({ ...s, row: sAtlas.rows[i] }))), new MeshBasicMaterial({ map: sAtlas.texture, vertexColors: true, toneMapped: false }));
    const bMesh = new Mesh(quads(boards.map(s => ({ ...s, row: bAtlas.rows[s.slot!] })), .006), new MeshStandardMaterial({ map: bAtlas.texture, roughness: .9 }));
    sMesh.name = 'town-signs'; bMesh.name = 'town-boards';
    for (const m of [sMesh, bMesh]) { m.receiveShadow = m === bMesh; m.userData.noOcclusionFade = true; }
    return { sMesh, bMesh, signSlots: signs.map(s => s.slot!),
      boardPos: boards.map(b => ({ slot: b.slot!, position: b.position.toArray() as Vec3 })),
      dispose: () => { for (const m of [sMesh, bMesh]) { m.geometry.dispose(); (m.material as MeshBasicMaterial).map?.dispose(); (m.material as Material).dispose(); } } };
  }, [built, en, zh, ids]);
  useEffect(() => canvases.dispose, [canvases]);
  // palm wind (paused / screenshot mode freezes through the shared wind uniforms)
  useEffect(() => { const off = built.palms.map(m => attachNatureWind(m)); return () => off.forEach(f => f()); }, [built]);
  const pillars = useMemo(() => BUILDINGS.map(({ position: [x, , z], size: [w] }) => [x + w / 2 + 5, z] as [number, number]), []);
  const level = useRef(BUILDINGS.map(() => 0));
  const group = useRef<import('three').Group>(null);
  const camera = useThree(s => s.camera);
  useFrame((_, dt) => {
    const n = night.value, [px, , pz] = useWorldStore.getState().position;
    glow.glass.value = .04 + n * 1.25;
    glow.ring.value = .12 + n * .55;
    const step = Math.min(.1, dt);
    pillars.forEach(([x, z], i) => {
      const near = Math.hypot(px - x, pz - z) < LIGHT_RADIUS ? 1 : 0;
      level.current[i] += (near - level.current[i]) * (1 - Math.exp(-step * (near ? 6 : 1.4)));
    });
    const L = level.current;
    const strip = built.strips;
    if (strip) {
      const slot = strip.geometry.getAttribute('slot'), col = strip.geometry.getAttribute('color') as BufferAttribute;
      for (let i = 0; i < col.count; i++) { const k = .18 + .42 * n + L[slot.getX(i)] * (.55 + .45 * n); col.setXYZ(i, .31 * k, .82 * k, .77 * k); }
      col.needsUpdate = true;
    }
    const tint = (mesh: Mesh, slots: number[], base: number, lit: number) => {
      const col = mesh.geometry.getAttribute('color') as BufferAttribute;
      slots.forEach((s, q) => { const k = base + (lit - base) * L[s]; for (let j = 0; j < 4; j++) col.setXYZ(q * 4 + j, k, k, k); });
      col.needsUpdate = true;
    };
    tint(canvases.sMesh, canvases.signSlots, .62 - .3 * n, 1);
    // region LOD: beyond 60 m from a region's bounds, its merged detail swaps to the hull LOD1
    for (const r of Object.values(built.regions)) {
      if (!r.lod) continue;
      const far = camera.position.distanceTo(r.center) - r.radius > 60;
      r.lod.visible = far; r.meshes.forEach(m => { m.visible = !far; });
    }
  });
  useEffect(() => {
    if (new URLSearchParams(window.location.search).get('qa') !== '1') return;
    Object.assign(window, { __worldTown: { stats: () => ({ ...built.stats, signs: canvases.signSlots.length, years: 0, boards: canvases.boardPos.length }),
      levels: () => [...level.current], setVisible: (on: boolean) => { if (group.current) group.current.visible = on; return on; }, bodies: () => built.bodies.map(b => ({ name: b.name, hulls: b.hulls.length })),
      lod: () => Object.fromEntries(Object.entries(built.regions).map(([k, r]) => [k, { far: !!r.lod?.visible, center: r.center.toArray(), radius: r.radius }])) } });
    return () => { delete (window as unknown as Record<string, unknown>).__worldTown; };
  }, [built, canvases]);
  return <group ref={group} name="world-town-assets">
    {Object.entries(built.regions).map(([r, reg]) => <group key={r} name={`town-region-${r}`}>
      {reg.meshes.map(m => <primitive key={m.uuid} object={m} />)}
      {reg.lod && <primitive object={reg.lod} />}
    </group>)}
    {built.palms.map(m => <primitive key={m.uuid} object={m} />)}
    {built.strips && <primitive object={built.strips} />}
    <primitive object={built.shadow} />
    <primitive object={canvases.sMesh} />
    <primitive object={canvases.bMesh} />
    {built.bodies.map(b => <RigidBody key={b.name} name={`town-body-${b.name}`} type="fixed" colliders={false}
      userData={{ solid: true, assetId: b.asset, ...(b.interactable ? { interactable: b.interactable } : {}) }}>
      {b.hulls.map((h, i) => <ConvexHullCollider key={i} name={`town-collider-${b.name}-${i}`} args={[h]} friction={.65} restitution={.12} />)}
    </RigidBody>)}
    {!LAYOUT_V4 && <RigidBody type="fixed" colliders={false} userData={{ surface: true }}>
      {/* v3 fallback: the claimed greybox forecourt slab is replaced one-for-one (v4 forecourts are paved). */}
      {BUILDINGS.map(({ id, position: [x, y, z], size: [w, , d] }) => <CuboidCollider key={id} args={[2.7, .035, d / 2 + .5]} position={[x + w / 2 + 2.7, y + .035, z]} />)}
    </RigidBody>}
    {!LAYOUT_V4 && BUILDINGS.map(({ id, position: [x, y, z], size: [w, , d] }) => <mesh key={id} position={[x + w / 2 + 2.7, y + .035, z]} receiveShadow userData={{ surface: true }}>
      <boxGeometry args={[5.4, .07, d + 1]} /><meshStandardMaterial color="#D9D2C2" roughness={.95} />
    </mesh>)}
    {canvases.boardPos.map(b => en[b.slot] && zh[b.slot] ? <Board key={b.slot} slot={b.slot} position={b.position} en={en[b.slot]} zh={zh[b.slot]} /> : null)}
  </group>;
}
