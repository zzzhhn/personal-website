/**
 * Town district formal assets (docs/world/town/DESIGN.md). Every GLB is generated by
 * tools/world/town/build_town.py. Visuals are merged per material and per region (town / west shore /
 * south beach) so the whole district costs a fixed handful of draw calls; colliders are the GLBs' own
 * `col_*` convex hulls placed with the same matrices as the visuals (door openings, porches and the
 * arcade stay walkable because the hulls never fill them). Sun shadows come from one merged proxy
 * built from the same hulls (roof tops lowered to the deck, openings left open).
 */

